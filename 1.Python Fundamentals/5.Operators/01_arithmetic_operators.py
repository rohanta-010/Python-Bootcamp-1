### Python REPL stands for:

# R – Read
# E – Evaluate
# P – Print
# L – Loop

## It describes how Python's interactive interpreter works.

## Here's what each step means:
# Read: Python reads the code you type.
# Evaluate: Python executes or evaluates that code.
# Print: Python displays the result (if there is one).
# Loop: Python waits for your next command and repeats the process



 